#!/usr/bin/env python3
"""
EvaluateCovering.py — Measure CoveringAttack.py results against ground truth.

Metrics (per netlist, then aggregated):

  Per-variant:
    n_variants                   total locked variants per netlist (sidecar)
    n_ok                         # extracted + table built successfully
    cluster_recovery_rate        fraction of variants for which the table
                                 admits >=1 covering (i.e. all input rows
                                 have at least one valid key)
    designer_match_rate          fraction of variants whose designer's
                                 (covering = partition + KS) is realizable
                                 within the table we computed.

  Per-key-bit:
    n_kbits_total                # lock_key bits across all variants
    n_kbits_recovered            # lock_key bits for which we computed at
                                 least one valid value via a recovered cov.
    kbit_recovery_rate           = recovered / total

  Multiplicity:
    mean_log10_candidates        log10 of geometric mean of
                                 product_I |valid_keys(I)| across variants.
                                 Empirical IDKLL multiplicity measure.

Dependencies:
    pip install pandas networkx tqdm pyarrow
"""

from __future__ import annotations

import argparse
import concurrent.futures as cf
import json
import math
import os
import pickle
import sys
import traceback
from pathlib import Path

import networkx as nx
import pandas as pd
from tqdm import tqdm


def build_truth_lookup(sidecar: dict) -> dict:
    """
    Builds a structured lookup table of the designer's true key coverings.

    For each locked variant in the sidecar, extracts:
       Y_bit -> {
         'A_bit', 'B_bit', 'K_bits',
         'designer_covering': sorted list of (input_set_tuple, key_tuple)
       }

    Args:
        sidecar (dict): The parsed GateLock JSON sidecar containing ground truth.

    Returns:
        dict: A mapping of Y_bit identifiers to their true structural and covering data.
    """
    out = {}
    for entry in sidecar.get("locked_gates", []):
        n_data = 1 if entry.get("B_bit") is None else 2
        a_bit, b_bit = entry["A_bit"], entry.get("B_bit")
        # Group valid_key_sequences by their key value
        cov = {}
        for ks in entry.get("valid_key_sequences", []):
            inp = (ks["gate_input_A"],) if n_data == 1 \
                  else (ks["gate_input_A"], ks["gate_input_B"])
            k_tup = tuple(int(c) for c in ks["valid_key_sequence"])
            cov.setdefault(k_tup, []).append(inp)
        designer_cov = sorted([(tuple(sorted(inps)), k)
                               for k, inps in cov.items()],
                              key=lambda x: (x[1], x[0]))
        out[entry["Y_bit"]] = {
            "A_bit":             a_bit,
            "B_bit":             b_bit,
            "K_bits":            list(entry["K_bits"]),
            "designer_covering": designer_cov,
        }
    return out


def designer_realizable(table_obj: dict, designer_cov: list, n_data: int,
                        attack_data_bits: list, sidecar_a: int, sidecar_b: int | None) -> bool:
    """
    Verifies if the attacker's derived truth table can perfectly realize the designer's covering.

    Given the attack's truth table (keyed by '|'-joined input bits in attack_data_bits order) 
    and the designer's covering (whose input tuples are in (A,B) order from the sidecar), 
    checks whether every designer (input, key) row is a valid entry in the table.

    Args:
        table_obj (dict): The truth table generated by CoveringAttack.py.
        designer_cov (list): The ground-truth covering from the sidecar.
        n_data (int): Number of data bits (1 or 2).
        attack_data_bits (list): The ordered list of data bit IDs used by the attack.
        sidecar_a (int): The true A_bit ID from the sidecar.
        sidecar_b (int | None): The true B_bit ID from the sidecar, if applicable.

    Returns:
        bool: True if the designer's covering exists within the attack table, False otherwise.
    """
    # Build permutation: sidecar's (A,[B]) -> attack's data_bits order
    if n_data == 1:
        sidecar_bits_in_order = [sidecar_a]
    else:
        sidecar_bits_in_order = [sidecar_a, sidecar_b]
    try:
        perm = [sidecar_bits_in_order.index(b) for b in attack_data_bits]
    except ValueError:
        return False

    for (input_set, K) in designer_cov:
        for inp_sidecar in input_set:
            # rearrange to attack's input ordering
            inp_attack = tuple(inp_sidecar[i] for i in perm)
            key_str = ",".join(str(x) for x in inp_attack)
            if key_str not in table_obj:
                return False
            valid = [tuple(k) for k in table_obj[key_str]]
            if K not in valid:
                return False
    return True


def evaluate_one(args: tuple) -> tuple:
    """
    Worker job to evaluate the covering attack success for a single netlist.

    Args:
        args (tuple): (stem, cov_pq_path, cache_pkl, key_path)

    Returns:
        tuple: Worker status flag, stem identifier, and a dictionary of extracted metrics.
    """
    (stem, cov_pq_path, cache_pkl, key_path) = args
    try:
        cov_df = pd.read_parquet(cov_pq_path)
        sidecar = json.loads(Path(key_path).read_text())
        truth = build_truth_lookup(sidecar)

        n_variants = len(cov_df)
        n_ok = int(cov_df["ok"].sum()) if "ok" in cov_df.columns else 0
        n_recovered = 0
        n_designer_match = 0
        log_cands = []
        recovered_kbits = set()
        true_kbits_total = set()
        for entry in sidecar.get("locked_gates", []):
            true_kbits_total.update(entry.get("K_bits", []))

        for _, row in cov_df.iterrows():
            if not row.get("ok", False):
                continue
            y_bit = row["y_bit"]
            t = truth.get(y_bit)
            if t is None:
                continue   # variant in attack output but not sidecar (shouldn't happen)

            n_cand = int(row.get("n_candidates", 0))
            if n_cand > 0:
                log_cands.append(math.log10(n_cand))

            table_obj = json.loads(row["table"]) if row.get("table") else {}
            attack_data_bits = json.loads(row.get("data_bits", "[]"))
            attack_k_bits    = json.loads(row.get("k_bits", "[]"))

            # Cluster is "recovered" iff every input row has at least one valid key
            recovered = (len(table_obj) > 0 and
                         all(len(v) > 0 for v in table_obj.values()))
            if recovered:
                n_recovered += 1
                recovered_kbits.update(attack_k_bits)

            # Designer match: is the designer's covering in the table?
            if designer_realizable(table_obj, t["designer_covering"],
                                   1 if t["B_bit"] is None else 2,
                                   attack_data_bits,
                                   t["A_bit"], t["B_bit"]):
                n_designer_match += 1

        cluster_rec_rate = n_recovered / n_variants if n_variants else 0.0
        designer_rate    = n_designer_match / n_variants if n_variants else 0.0
        mean_log_cand    = (sum(log_cands) / len(log_cands)) if log_cands else 0.0

        return ("ok", stem, {
            "n_variants":            n_variants,
            "n_ok":                  n_ok,
            "n_recovered":           n_recovered,
            "cluster_recovery_rate": cluster_rec_rate,
            "n_designer_match":      n_designer_match,
            "designer_match_rate":   designer_rate,
            "mean_log10_candidates": mean_log_cand,
            "n_kbits_total":         len(true_kbits_total),
            "n_kbits_recovered":     len(recovered_kbits),
            "kbit_recovery_rate":    (len(recovered_kbits) /
                                       max(len(true_kbits_total), 1)),
        })
    except Exception as e:
        return ("err", stem, f"{type(e).__name__}: {e}\n{traceback.format_exc()}")


def main():
    """Parses arguments, evaluates all covering attacks against ground truth, and writes summary reports."""
    ap = argparse.ArgumentParser(
        description="Measure CoveringAttack.py recovery and exact-match success rates against GateLock ground truth."
    )
    ap.add_argument("--cache-dir", required=True,
                    help="Directory containing the serialized graph pickles and the manifest.")
    ap.add_argument("--covering-dir", required=True,
                    help="Directory containing the <stem>.covering.parquet files produced by CoveringAttack.py.")
    ap.add_argument("--sidecar-dir", required=True,
                    help="Directory containing the original GateLock *.key.json sidecar files (Ground Truth).")
    ap.add_argument("--out-prefix", required=True,
                    help="Filename prefix for the generated CSV evaluation reports (e.g., 'results/covering_eval').")
    ap.add_argument("--workers", type=int, default=None,
                    help="Number of concurrent multiprocessing workers.")
    ap.add_argument("--no-progress", action="store_true",
                    help="Disable TQDM progress bar output.")
    args = ap.parse_args()

    cache_dir   = Path(args.cache_dir).resolve()
    cov_dir     = Path(args.covering_dir).resolve()
    sidecar_dir = Path(args.sidecar_dir).resolve()
    out_prefix  = Path(args.out_prefix).resolve()
    out_prefix.parent.mkdir(parents=True, exist_ok=True)

    cov_files = sorted(cov_dir.glob("*.covering.parquet"))
    if not cov_files:
        raise SystemExit(f"no *.covering.parquet in {cov_dir}")

    manifest = pd.read_parquet(cache_dir / "manifest.parquet")
    locked = manifest[manifest["kind"] == "locked"]
    pkl_of = {}
    for _, row in locked.iterrows():
        p = cache_dir / "locked" / row["circuit"] / f"{row['stem']}.pkl"
        if not p.exists():
            stored = Path(row["path"])
            p = stored if stored.is_absolute() else (cache_dir / stored)
        pkl_of[row["stem"]] = p

    jobs = []
    for cf_path in cov_files:
        stem = cf_path.name[:-len(".covering.parquet")]
        pkl = pkl_of.get(stem)
        kp = sidecar_dir / f"{stem}.key.json"
        if not pkl or not kp.exists():
            continue
        jobs.append((stem, cf_path, pkl, kp))

    workers = args.workers or max(1, (os.cpu_count() or 2) - 1)
    print(f"covering dir: {cov_dir}")
    print(f"to do:        {len(jobs)}")
    print(f"workers:      {workers}\n")

    rows = []
    errors = []
    if workers == 1:
        it = (evaluate_one(j) for j in jobs)
    else:
        ex = cf.ProcessPoolExecutor(max_workers=workers)
        it = ex.map(evaluate_one, jobs)
    for r in tqdm(it, total=len(jobs), desc="eval", disable=args.no_progress):
        if r[0] == "err":
            errors.append(r)
        else:
            rows.append({"stem": r[1], **r[2]})
    if workers != 1:
        ex.shutdown()

    if rows:
        df = pd.DataFrame(rows)
        df.to_csv(str(out_prefix) + ".per_file.csv", index=False)
        summary = pd.DataFrame({
            "metric": [
                "cluster_recovery_rate (mean)",
                "designer_match_rate   (mean)",
                "kbit_recovery_rate    (mean)",
                "mean_log10_candidates (mean)",
                "n_variants            (sum)",
                "n_recovered           (sum)",
                "n_kbits_total         (sum)",
                "n_kbits_recovered     (sum)",
            ],
            "value": [
                df["cluster_recovery_rate"].mean(),
                df["designer_match_rate"].mean(),
                df["kbit_recovery_rate"].mean(),
                df["mean_log10_candidates"].mean(),
                df["n_variants"].sum(),
                df["n_recovered"].sum(),
                df["n_kbits_total"].sum(),
                df["n_kbits_recovered"].sum(),
            ],
        })
        summary.to_csv(str(out_prefix) + ".summary.csv", index=False)
        print("\nSummary:")
        print(summary.round(4).to_string(index=False))
        print(f"\nwrote: {out_prefix}.per_file.csv ({len(df)} rows)")
        print(f"       {out_prefix}.summary.csv")

    if errors:
        from collections import Counter
        print(f"\n{len(errors)} error(s).")
        bucket = Counter(r[2].splitlines()[0] for r in errors)
        for msg, cnt in bucket.most_common(5):
            print(f"  {cnt:>4}  {msg}")
        print("first traceback:")
        print(errors[0][2])


if __name__ == "__main__":
    main()